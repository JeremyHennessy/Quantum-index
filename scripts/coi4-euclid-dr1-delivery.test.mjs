import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const r=JSON.parse(fs.readFileSync('research/COI4_EUCLID_DR1_FOUNDATION_DELIVERY_2026-11-12.json','utf8'));
const older=JSON.parse(fs.readFileSync('research/COI0_OBSERVATORY_AND_RELEASE_CENSUS_2026-10-30.json','utf8'));
const preflight=JSON.parse(fs.readFileSync('research/COI2_EUCLID_DR1_PRODUCT_SPLIT_2026-11-06.json','utf8'));
const sourceIds=new Set(['esa-release','irsa-overview','irsa-sir-doi','nasa-foundation-scope','nasa-complete-scope']);
function verify(d){
 assert.equal(d.schemaVersion,'coi4-euclid-foundation-delivery-v1');
 assert.equal(d.reviewedAt,'2026-11-12');
 assert.equal(d.publicationStatus,'RESEARCH_ONLY_NOT_RUNTIME');
 assert.match(d.baselineMainSha,/^[a-f0-9]{40}$/);
 assert.equal(d.baselineMainSha,'53af2bfc6cc4d744e9f3f89cf2f1ede7ff36eb90');
 assert.equal(d.historicalPreflight,'research/COI2_EUCLID_DR1_PRODUCT_SPLIT_2026-11-06.json');
 assert.deepEqual(d.existingIds,preflight.existingIds);
 assert.equal(new Set(d.sources.map(x=>x.id)).size,5);
 assert.equal(new Set(d.sources.map(x=>x.url)).size,5);
 for(const s of d.sources){assert.ok(sourceIds.has(s.id));assert.equal(s.checkedAt,'2026-11-12');assert.match(s.url,/^https:\/\//);}
 assert.equal(d.sources.find(x=>x.id==='esa-release').publishedOn,'2026-11-12');
 assert.equal(d.sources.find(x=>x.id==='irsa-overview').url,'https://irsa.ipac.caltech.edu/data/Euclid/docs/overview_dr1.html');
 assert.equal(d.sources.find(x=>x.id==='irsa-sir-doi').url,'https://www.ipac.caltech.edu/doi/10.26131/IRSA680');
 const f=d.foundation,c=d.complete;
 assert.equal(f.actualReleaseDate,'2026-11-12'); assert.equal(f.status,'released-confirmed-by-ESA-and-IRSA');
 assert.equal(f.publicReleaseDeclared,true);
 assert.deepEqual(new Set(f.sourceIds),new Set(['esa-release','irsa-overview']));
 assert.equal(f.archiveDocumentationRetrieved,true);assert.equal(f.productDoiRecordRetrieved,true);
 assert.equal(f.individualFileDownloadVerified,false);
 assert.equal(f.fullCatalogServiceCompletenessVerified,false);
 assert.equal(f.interactiveDataSpaceQueryVerified,false);
 assert.match(f.accessCaveat,/incrementally over the coming weeks/i);
 assert.equal(f.estimatedWideSurveyAreaSqDeg,1900);
 assert.equal(f.esaApproxMillionGB,1.7);
 assert.equal(f.irsaApproxPB,1.8);
 assert.equal(f.reportedCounts.galaxiesMoreThan,900000000);
 assert.equal(f.reportedCounts.strongLensingCandidatesApprox,15000);
 assert.equal(f.reportedCounts.quasarCandidatesMoreThan,60000000);
 assert.equal(f.reportedCounts.spectraSourcesMoreThan,160000000);
 assert.match(f.countsQualification,/not independent/i);
 assert.ok(f.includedProductFamilies.some(x=>x.startsWith('LE1')));
 assert.ok(f.includedProductFamilies.some(x=>x.startsWith('LE2')));
 assert.equal(f.specificProduct.doi,'10.26131/IRSA680');
 assert.equal(f.specificProduct.sourceId,'irsa-sir-doi');
 assert.equal(f.specificProduct.individualFileRetrieved,false);
 assert.equal(f.scientificEvidencePromoted,false);
 assert.equal(f.claimStatus,'OFFICIAL_DATA_RELEASE_METADATA_NOT_SCIENCE_EVIDENCE');
 assert.equal(c.expected,'mid-2027');assert.equal(c.dateStatus,'future-not-actual');
 assert.equal(c.confirmedReleased,false);assert.equal(c.actualReleaseDate,null);
 assert.ok(c.highLevelProductsExpected.some(x=>x.includes('weak-lensing')));
 assert.ok(c.highLevelProductsExpected.some(x=>x.includes('galaxy-clustering')));
 assert.equal(c.scientificEvidencePromoted,false);
 for(const id of [...c.sourceIds,...f.sourceIds])assert.ok(sourceIds.has(id));
 assert.equal(d.scienceAdmission.status,'NO_NEW_COSMOLOGICAL_CONSTRAINT');
 for(const key of ['darkEnergyMeasurementAdmitted','darkMatterTheoryValidated','weakLensingLikelihoodReleased'])assert.equal(d.scienceAdmission[key],false);
 assert.match(d.scienceAdmission.requirements,/uncertainties\/covariance/);
 assert.equal(d.mergeGate,'DRAFT_ONLY_PENDING_EXACT_HEAD_NODE_CHROMIUM_WEBKIT_AND_SCREENSHOTS');
 assert.ok(d.preservation.includes('approved Explorer HTML/CSS/JS'));
 return true;
}
test('COI-4 references actual older Euclid records and retains the dated preflight',()=>{
 verify(r);
 const ids=r.existingIds;
 assert.ok(older.programmes.some(x=>x.id===ids.programmeId));
 assert.ok(older.releases.some(x=>x.id===ids.publicQuickReleaseId));
 assert.ok(older.releases.some(x=>x.id===ids.foundationReleaseId));
 assert.ok(older.milestones.some(x=>x.id===ids.foundationMilestoneId));
 assert.equal(preflight.foundation.confirmedActual,false);
 assert.equal(preflight.foundation.dateStatus,'planned');
});
